// Emits the semantic-topic vocabulary the Rust policy kernel embeds.
//
// The kernel is the single evaluator; the vocabulary it matches against is
// authored in TypeScript (packages/policy-schema/src/semantic-topics.ts) and
// extracted here so the two cannot drift. This script derives data only — it
// runs no evaluator and records no expected verdict.
//
// Output:
//   packages/policy-schema/native/src/generated/semantic_topics.json
//       Embedded into the crate via include_str!. It lives inside the crate
//       root because include_str! cannot reach outside it, and the container
//       images build the crate from its own directory.
//
// Usage:
//   node --import tsx scripts/generate-worker-policy-data.mjs           # write
//   node --import tsx scripts/generate-worker-policy-data.mjs --check   # verify
//
// --check is what CI runs: it regenerates in memory and fails if the checked-in
// file differs, so editing the TypeScript tables without regenerating is caught
// in review rather than becoming a silent divergence from the kernel.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SEMANTIC_OUT_RUST = join(
  ROOT,
  "packages/policy-schema/native/src/generated/semantic_topics.json",
);
// The conformance fixtures under conformance/ are deliberately not generated.
// They are reviewed contract artifacts, so no implementation can silently
// rewrite the outcomes it is held to.

const BANNER = "GENERATED by scripts/generate-worker-policy-data.mjs — do not edit by hand.";

const { SEMANTIC_TOPICS, SEMANTIC_STOP_WORDS, SEMANTIC_GENERIC_WORDS, SEMANTIC_MATCH_RATIO } =
  await import("../packages/policy-schema/src/semantic-topics.ts");

function buildSemanticTopics() {
  return {
    _generated: BANNER,
    // Order is significant: topics are evaluated in sequence, first match wins.
    topics: SEMANTIC_TOPICS.map((topic) => ({
      id: topic.id,
      promptTriggers: topic.promptTriggers,
      keywords: topic.keywords,
    })),
    stopWords: SEMANTIC_STOP_WORDS,
    genericWords: SEMANTIC_GENERIC_WORDS,
    matchRatio: SEMANTIC_MATCH_RATIO,
  };
}

function serialize(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

const outputs = [{ path: SEMANTIC_OUT_RUST, content: serialize(buildSemanticTopics()) }];

if (process.argv.includes("--check")) {
  const stale = [];
  for (const { path, content } of outputs) {
    const relative = path.replace(`${ROOT}/`, "");
    let existing = null;
    try {
      existing = readFileSync(path, "utf8");
    } catch {
      stale.push(`${relative}: missing`);
      continue;
    }
    if (existing !== content) stale.push(`${relative}: out of date`);
  }
  if (stale.length > 0) {
    console.error("Generated policy kernel data is stale.");
    console.error("Run: pnpm generate:worker-policy-data\n");
    for (const entry of stale) console.error(`  - ${entry}`);
    process.exit(1);
  }
  console.log("Worker policy data check passed.");
} else {
  for (const { path, content } of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path.replace(`${ROOT}/`, "")}`);
  }
}
