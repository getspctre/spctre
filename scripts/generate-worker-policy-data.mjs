// Emits the shared policy data the Go decision engine consumes.
//
// The gateway decision path exists twice — TypeScript in apps/web and Go in
// apps/worker — because the worker serves delegated decide traffic. Only the
// matching *logic* is written twice; the data both engines match against is
// generated here from the TypeScript source of truth so it cannot drift.
//
// Outputs:
//   apps/worker/internal/worker/semantic_topics.json
//       Vocabulary for classifySemanticIntent, embedded into the worker binary
//       via go:embed. Generated from packages/policy-schema/src/semantic-topics.
//   conformance/policy-packs.json
//       Pack rules for the connectors that have conformance fixtures, so the Go
//       conformance test evaluates the identical rules the TypeScript test does.
//   conformance/semantic-intent.json
//       Expected classifySemanticIntent verdicts across a matrix derived from
//       the topic tables, so the Go semantic matcher is held to the TypeScript
//       implementation's exact behaviour rather than to a handful of examples.
//
// Usage:
//   node --import tsx scripts/generate-worker-policy-data.mjs           # write
//   node --import tsx scripts/generate-worker-policy-data.mjs --check   # verify
//
// --check is what CI runs: it regenerates in memory and fails if the checked-in
// files differ, so editing the TypeScript tables without regenerating is caught
// in review rather than becoming a silent divergence between the two engines.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURES_ROOT = join(ROOT, "packages/policy-schema/tests/fixtures/packs");
const SEMANTIC_OUT = join(ROOT, "apps/worker/internal/worker/semantic_topics.json");
const PACKS_OUT = join(ROOT, "conformance/policy-packs.json");
const SEMANTIC_CASES_OUT = join(ROOT, "conformance/semantic-intent.json");
// `conformance/policy-rules.json` is intentionally not generated. It is a
// reviewed evaluator-contract fixture, so TypeScript cannot silently rewrite
// expected outcomes when its implementation changes.

const BANNER = "GENERATED by scripts/generate-worker-policy-data.mjs — do not edit by hand.";
// This version names the portable, published-rule evaluator contract rather
// than an implementation. Consumers must reject a future incompatible major
// version instead of silently evaluating a bundle with different semantics.
const PUBLISHED_EVALUATOR_CONTRACT_VERSION = "1.0";

const { SEMANTIC_TOPICS, SEMANTIC_STOP_WORDS, SEMANTIC_GENERIC_WORDS, SEMANTIC_MATCH_RATIO } =
  await import("../packages/policy-schema/src/semantic-topics.ts");
const { POLICY_PACKS } = await import("../packages/policy-schema/src/packs.ts");
const { classifySemanticIntent, evaluateDecision, composePolicyLayers } =
  await import("../packages/policy-schema/src/schema.ts");

/** Connectors with a conformance fixture directory, derived so it cannot drift. */
function connectorsWithFixtures() {
  return readdirSync(FIXTURES_ROOT, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

function buildSemanticTopics() {
  return {
    _generated: BANNER,
    // Order is significant: topics are evaluated in sequence, first match wins.
    topics: SEMANTIC_TOPICS.map((topic) => ({
      id: topic.id,
      promptTriggers: topic.promptTriggers,
      keywords: topic.keywords,
    })),
    stopWords: SEMANTIC_STOP_WORDS,
    genericWords: SEMANTIC_GENERIC_WORDS,
    matchRatio: SEMANTIC_MATCH_RATIO,
  };
}

function buildPackRules() {
  const byConnector = {};
  for (const connector of connectorsWithFixtures()) {
    const pack = POLICY_PACKS.find((candidate) => candidate.connector === connector);
    if (!pack) throw new Error(`No pack registered for connector with fixtures: ${connector}`);
    // Mirrors rulesForConnector() in tests/pack-fixtures.test.ts.
    byConnector[connector] = pack.rules.map((rule) => ({
      ...rule,
      sourceFormat: "SPCTRE_MANAGED",
    }));
  }
  return { _generated: BANNER, packs: byConnector };
}

/**
 * Builds the semantic-intent conformance matrix.
 *
 * Derived from the topic tables rather than hand-written, so a topic or keyword
 * added to semantic-topics.ts automatically grows the corpus the Go engine is
 * held to. Expected verdicts are computed by the TypeScript implementation,
 * which is the reference.
 */
function buildSemanticCases() {
  const cases = [];
  const add = (input) =>
    cases.push({
      ...input,
      expected: classifySemanticIntent(
        input.prompt,
        input.toolIntent ?? "",
        input.planSummary ?? "",
        input.toolParameters ?? {},
      ),
    });

  for (const topic of SEMANTIC_TOPICS) {
    for (const trigger of topic.promptTriggers) {
      // Trigger with each of its own keywords present — the positive path.
      for (const keyword of topic.keywords) {
        add({ prompt: `${trigger} concern`, toolIntent: `request mentions ${keyword}` });
        add({ prompt: `${trigger} concern`, planSummary: `plan mentions ${keyword}` });
        add({ prompt: `${trigger} concern`, toolParameters: { note: keyword } });
      }
      // Trigger with nothing to confirm it — must fall through to the token
      // fallback rather than matching on the trigger alone.
      add({ prompt: `${trigger} concern`, toolIntent: "unrelated benign request" });
    }
    // A keyword present but no trigger in the prompt: topic must not fire.
    add({ prompt: "routine maintenance", toolIntent: `mentions ${topic.keywords[0]}` });
  }

  // Quoted patterns: once the prompt quotes anything, only quotes decide.
  for (const quoted of ["rm -rf", "social security", "not present anywhere"]) {
    add({ prompt: `contains "${quoted}"`, toolIntent: "rm -rf / and social security" });
    add({ prompt: `contains "${quoted}"`, toolIntent: "nothing of note" });
    add({ prompt: `"${quoted}" and delete`, toolIntent: "delete everything" });
  }

  // Token-overlap fallback, including generic-word-only prompts.
  const fallbackPrompts = [
    "escalate every filed brief",
    "read file",
    "run command",
    "show data value",
    "transfer funds to unknown account",
    "the of and to for",
    "",
    "   ",
  ];
  const fallbackSpaces = [
    "",
    "escalate every filed brief",
    "escalate brief",
    "read file",
    "transfer funds",
    "completely unrelated text",
  ];
  for (const prompt of fallbackPrompts) {
    for (const toolIntent of fallbackSpaces) {
      add({ prompt, toolIntent });
    }
  }

  // Parameter-bearing cases. Go sorts map keys where JavaScript preserves
  // insertion order, so multi-key parameters are deliberately included.
  const parameterCases = [
    {},
    { statement_type: "DROP" },
    { amount: 25000, currency: "usd" },
    { zebra: "last", alpha: "first", middle: "rm -rf /" },
    { nested: { deep: { value: "social security" } } },
    { list: ["password", "token"] },
  ];
  for (const toolParameters of parameterCases) {
    for (const prompt of ["credential exposure", "destructive operation", "read file"]) {
      add({ prompt, toolParameters });
      add({ prompt, toolIntent: "context", toolParameters });
    }
  }

  return { _generated: BANNER, cases };
}

/**
 * Builds a synthetic rule corpus for behaviour the pack fixtures do not reach.
 *
 * The pack fixtures exercise realistic connector rules, but mutation testing
 * showed they never cover wildcard action patterns, parameter/semantic effect
 * overrides, or effect precedence among several matching rules — so a Go
 * regression in any of those would have gone unnoticed. These cases target
 * exactly those paths. Expected verdicts come from the TypeScript evaluator.
 */
function buildRuleCases() {
  const rule = (overrides) => ({
    stableRuleId: "r",
    title: "rule",
    effect: "ALLOW",
    sourceFormat: "SPCTRE_MANAGED",
    domains: [],
    connectors: [],
    actions: [],
    immutable: false,
    ...overrides,
  });

  const wildcard = [
    rule({ stableRuleId: "wildcard.deny", effect: "DENY", actions: ["billing.*"] }),
    rule({ stableRuleId: "exact.escalate", effect: "ESCALATE", actions: ["billing.refund"] }),
  ];
  const precedence = [
    rule({ stableRuleId: "p.warn", effect: "WARN", actions: ["act"] }),
    rule({ stableRuleId: "p.escalate", effect: "ESCALATE", actions: ["act"] }),
    rule({ stableRuleId: "p.deny", effect: "DENY", actions: ["act"] }),
  ];
  const parameterOverride = [
    rule({
      stableRuleId: "param.override",
      effect: "ALLOW",
      actions: ["charge"],
      parameterConstraints: [{ field: "amount", operator: "gt", value: 1000, effect: "DENY" }],
    }),
  ];
  const semanticOverride = [
    rule({
      stableRuleId: "semantic.override",
      effect: "ALLOW",
      actions: ["reply"],
      semanticChecks: [{ id: "s1", prompt: "credential exposure", effect: "ESCALATE" }],
    }),
  ];
  const operators = (operator, value) => [
    rule({
      stableRuleId: `op.${operator}`,
      effect: "DENY",
      actions: ["op"],
      parameterConstraints: [{ field: "field", operator, value }],
    }),
  ];
  const nestedPath = [
    rule({
      stableRuleId: "nested.path",
      effect: "DENY",
      actions: ["op"],
      parameterConstraints: [{ field: "branch.protected", operator: "eq", value: true }],
    }),
  ];
  const domainScoped = [
    rule({ stableRuleId: "domain.deny", effect: "DENY", actions: ["op"], domains: ["payments"] }),
  ];
  const matchAll = [rule({ stableRuleId: "match.all", effect: "WARN" })];

  const specs = [
    ["wildcard matches prefix", wildcard, { action: "billing.void" }],
    ["wildcard and exact both match", wildcard, { action: "billing.refund" }],
    ["wildcard does not match sibling prefix", wildcard, { action: "billingother" }],
    ["wildcard does not match unrelated", wildcard, { action: "shipping.void" }],
    ["deny outranks escalate and warn", precedence, { action: "act" }],
    [
      "parameter override raises ALLOW to DENY",
      parameterOverride,
      { action: "charge", toolParameters: { amount: 5000 } },
    ],
    [
      "parameter constraint unmet leaves rule unmatched",
      parameterOverride,
      { action: "charge", toolParameters: { amount: 10 } },
    ],
    [
      "parameter field absent leaves rule unmatched",
      parameterOverride,
      { action: "charge", toolParameters: {} },
    ],
    [
      "semantic override raises ALLOW to ESCALATE",
      semanticOverride,
      { action: "reply", toolIntent: "leaking a password token" },
    ],
    [
      "semantic check unmet leaves rule unmatched",
      semanticOverride,
      { action: "reply", toolIntent: "ordinary reply" },
    ],
    ["operator eq matches", operators("eq", "x"), { action: "op", toolParameters: { field: "x" } }],
    [
      "operator eq rejects type mismatch",
      operators("eq", "1"),
      { action: "op", toolParameters: { field: 1 } },
    ],
    [
      "operator neq matches",
      operators("neq", "x"),
      { action: "op", toolParameters: { field: "y" } },
    ],
    [
      "operator gte boundary",
      operators("gte", 10),
      { action: "op", toolParameters: { field: 10 } },
    ],
    ["operator lt matches", operators("lt", 10), { action: "op", toolParameters: { field: 9 } }],
    [
      "operator lte boundary",
      operators("lte", 10),
      { action: "op", toolParameters: { field: 10 } },
    ],
    [
      "operator in matches",
      operators("in", ["a", "b"]),
      { action: "op", toolParameters: { field: "b" } },
    ],
    [
      "operator in rejects absent",
      operators("in", ["a", "b"]),
      { action: "op", toolParameters: { field: "c" } },
    ],
    [
      "operator not_in matches",
      operators("not_in", ["a"]),
      { action: "op", toolParameters: { field: "c" } },
    ],
    [
      "operator contains matches",
      operators("contains", "ell"),
      { action: "op", toolParameters: { field: "hello" } },
    ],
    // Both sides strings but the needle absent — the only shape that catches a
    // `contains` that stops actually testing for the substring.
    [
      "operator contains rejects absent substring",
      operators("contains", "xyz"),
      { action: "op", toolParameters: { field: "hello" } },
    ],
    [
      "operator contains rejects non-string",
      operators("contains", "ell"),
      { action: "op", toolParameters: { field: 5 } },
    ],
    [
      "operator neq rejects on type mismatch",
      operators("neq", 1),
      { action: "op", toolParameters: { field: "1" } },
    ],
    [
      "operator in rejects non-array expectation",
      operators("in", "ab"),
      { action: "op", toolParameters: { field: "a" } },
    ],
    [
      "nested dot-path constraint",
      nestedPath,
      { action: "op", toolParameters: { branch: { protected: true } } },
    ],
    ["nested dot-path missing parent", nestedPath, { action: "op", toolParameters: {} }],
    ["domain-scoped rule matches on domain", domainScoped, { action: "op", domains: ["payments"] }],
    ["domain-scoped rule with no request domains still matches", domainScoped, { action: "op" }],
    [
      "domain-scoped rule skipped on other domain",
      domainScoped,
      { action: "op", domains: ["shipping"] },
    ],
    ["empty connectors and actions match anything", matchAll, { action: "anything" }],
    ["no rules at all", [], { action: "anything" }],
  ];

  const cases = specs.map(([description, rules, input]) => {
    const evaluated = evaluateDecision({
      connector: input.connector ?? "conn",
      action: input.action,
      domains: input.domains ?? [],
      rules,
      toolIntent: input.toolIntent ?? "",
      planSummary: input.planSummary ?? "",
      toolParameters: input.toolParameters ?? {},
    });
    return {
      description,
      rules,
      connector: input.connector ?? "conn",
      action: input.action,
      domains: input.domains ?? [],
      toolIntent: input.toolIntent ?? "",
      planSummary: input.planSummary ?? "",
      toolParameters: input.toolParameters ?? {},
      expected: { status: evaluated.status, matchedRefs: evaluated.matchedRefs },
    };
  });

  // Layer composition: later layers override by stableRuleId unless the earlier
  // rule is immutable.
  const layerSpecs = [
    [
      "workspace overrides organization",
      [
        { scope: "ORGANIZATION", rules: [rule({ stableRuleId: "shared", effect: "ALLOW" })] },
        { scope: "WORKSPACE", rules: [rule({ stableRuleId: "shared", effect: "DENY" })] },
      ],
    ],
    [
      "immutable organization rule resists override",
      [
        {
          scope: "ORGANIZATION",
          rules: [rule({ stableRuleId: "locked", effect: "DENY", immutable: true })],
        },
        { scope: "WORKSPACE", rules: [rule({ stableRuleId: "locked", effect: "ALLOW" })] },
      ],
    ],
    [
      "disjoint layers accumulate",
      [
        { scope: "ORGANIZATION", rules: [rule({ stableRuleId: "a" })] },
        { scope: "WORKSPACE", rules: [rule({ stableRuleId: "b" })] },
      ],
    ],
  ];

  const compositionCases = layerSpecs.map(([description, layers]) => {
    const composed = composePolicyLayers({
      id: "preview",
      branchId: "b",
      revisionId: "r",
      layers,
      composedArtifactHash: "sha256:test",
      composedAt: "1970-01-01T00:00:00.000Z",
    });
    return {
      description,
      layers,
      expectedRuleIds: composed.effectiveRules.map((r) => r.stableRuleId),
      expectedEffects: composed.effectiveRules.map((r) => r.effect),
      expectedConflictNotes: composed.conflictNotes,
    };
  });

  return {
    _generated: BANNER,
    contract: {
      evaluatorVersion: PUBLISHED_EVALUATOR_CONTRACT_VERSION,
      requestSchemaVersion: "1.0",
      resultSchemaVersion: "1.0",
    },
    cases,
    compositionCases,
  };
}

function serialize(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

const outputs = [
  { path: SEMANTIC_OUT, content: serialize(buildSemanticTopics()) },
  { path: PACKS_OUT, content: serialize(buildPackRules()) },
  { path: SEMANTIC_CASES_OUT, content: serialize(buildSemanticCases()) },
];

if (process.argv.includes("--check")) {
  const stale = [];
  for (const { path, content } of outputs) {
    const relative = path.replace(`${ROOT}/`, "");
    let existing = null;
    try {
      existing = readFileSync(path, "utf8");
    } catch {
      stale.push(`${relative}: missing`);
      continue;
    }
    if (existing !== content) stale.push(`${relative}: out of date`);
  }
  if (stale.length > 0) {
    console.error("Generated worker policy data is stale.");
    console.error("Run: pnpm generate:worker-policy-data\n");
    for (const entry of stale) console.error(`  - ${entry}`);
    process.exit(1);
  }
  console.log("Worker policy data check passed.");
} else {
  for (const { path, content } of outputs) {
    writeFileSync(path, content);
    console.log(`wrote ${path.replace(`${ROOT}/`, "")}`);
  }
}
