function renderWorkflow(): string {
  return `# GitHub Actions workflow to lint the Spctre connector pack rules.
# This ensures all rules are syntactically valid and comply with the pack catalog.

name: Lint Spctre Governance Pack

on:
  push:
    branches: [ main ]
  pull_request:
    branches: [ main ]

jobs:
  lint:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: 20

      - name: Install Spctre CLI
        run: npm install -g @spctre/cli

      - name: Lint Policy Pack Rules
        run: spctre lint rules.yaml
`;
}
